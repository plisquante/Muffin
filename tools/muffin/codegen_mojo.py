"""
Mojo 1.2 Code Generator.

Emits clean, GC-free, devirtualized Mojo 1.2 source code from a closed-world
`Hierarchy` and lifted `MethodIR`s.
"""

from __future__ import annotations

from dataclasses import dataclass

from .classfile import ACC_ABSTRACT, ClassFile, Member
from .hierarchy import ClassInfo, Hierarchy
from .ir import (
    KIND_D,
    KIND_F,
    KIND_I,
    KIND_J,
    KIND_R,
    LiftedBlock,
    MethodIR,
    Stmt,
    Val,
    jtype_to_kind,
    kind_default,
    kind_to_mojo,
    lift_method,
)
from .types import JType, mangle_class, mangle_method, safe_ident

# Minimal JDK / PrintStream runtime shims for early end-to-end tests.
BUILTIN_CALLS = {
    ("java/lang/Object", "<init>", "()V"): "noop",
    ("java/io/PrintStream", "println", "(I)V"): "println_val",
    ("java/io/PrintStream", "println", "(J)V"): "println_val",
    ("java/io/PrintStream", "println", "(F)V"): "println_val",
    ("java/io/PrintStream", "println", "(D)V"): "println_val",
    ("java/io/PrintStream", "println", "(Z)V"): "println_bool",
    ("java/io/PrintStream", "println", "(Ljava/lang/String;)V"): "println_str",
    ("java/lang/Math", "abs", "(I)I"): "abs_i",
    ("java/lang/Math", "max", "(II)I"): "max_ii",
    ("java/lang/Math", "min", "(II)I"): "min_ii",
}


def _mojo_int_cast(kind: str) -> str:
    return {"I": "Int32", "J": "Int64", "F": "Float32", "D": "Float64"}[kind]


@dataclass
class CodegenStats:
    classes_emitted: int = 0
    methods_emitted: int = 0
    calls_devirtualized: int = 0
    calls_virtual: int = 0


def emit_mojo_program(
    hierarchy: Hierarchy,
    *,
    entry_class: str | None = None,
) -> tuple[str, CodegenStats]:
    """Emit a self-contained Mojo 1.2 module for all classes in `hierarchy`."""
    stats = CodegenStats()
    out: list[str] = []
    w = out.append

    w('"""Generated by Muffin (Java bytecode -> Mojo 1.2, zero-GC ARC + CHA)."""')
    w("")
    w("from std.ffi import external_call")
    w("from std.memory import OptionalPointer, Pointer")
    w("from std.origin import MutUntrackedOrigin")
    w("from std.sys import size_of")
    w("from runtime.muffin import (")
    w("    JArrayData,")
    w("    JRef,")
    w("    JThrowable,")
    w("    ObjHeader,")
    w("    RawFn,")
    w("    alloc_raw,")
    w("    array_get,")
    w("    array_len,")
    w("    array_set,")
    w("    check_cast,")
    w("    free_raw,")
    w("    is_instance,")
    w("    new_array,")
    w("    new_string,")
    w("    string_value,")
    w(")")
    w("")
    w("comptime JStaticsPtr = Pointer[JStatics, MutUntrackedOrigin]")
    w("")

    # 1. Static fields aggregate struct (no mutable module-level globals in Mojo 1.2)
    w("struct JStatics(Defaultable):")
    static_fields: list[tuple[str, str, str]] = []
    for cname in sorted(hierarchy.classes):
        ci = hierarchy.classes[cname]
        for fl in ci.static_fields:
            sname = f"sf_{mangle_class(cname)[2:]}_{safe_ident(fl.name)}"
            mtype = kind_to_mojo(jtype_to_kind(JType(fl.descriptor)))
            mdef = kind_default(jtype_to_kind(JType(fl.descriptor)))
            static_fields.append((sname, mtype, mdef))
    if not static_fields:
        w("    var _unused: Int32")
        w("    def __init__(out self):")
        w("        self._unused = 0")
    else:
        for sname, mtype, _ in static_fields:
            w(f"    var {sname}: {mtype}")
        w("    def __init__(out self):")
        for sname, _, mdef in static_fields:
            w(f"        self.{sname} = {mdef}")
    w("")

    # 2. Class structs + drop + allocator per concrete/abstract class
    for cname in sorted(hierarchy.classes):
        ci = hierarchy.classes[cname]
        if ci.cf.is_interface:
            continue
        stats.classes_emitted += 1
        sname = mangle_class(cname) + "Data"
        w(f"struct {sname}:")
        w("    var hdr: ObjHeader")
        for fl in ci.all_fields:
            mtype = kind_to_mojo(jtype_to_kind(JType(fl.descriptor)))
            w(f"    var f_{safe_ident(fl.mojo_name)}: {mtype}")
        w("")
        w(f"def drop_{mangle_class(cname)}(p: Pointer[ObjHeader, MutUntrackedOrigin]):")
        w(f"    var op = p.unsafe_bitcast[{sname}]()")
        w("    op.unsafe_deinit_pointee()")
        w("    free_raw(op)")
        w("")
        w(f"def new_{mangle_class(cname)}() raises JThrowable -> JRef:")
        w(f"    var raw = alloc_raw[{sname}]()")
        w(f"    raw[].hdr = ObjHeader({ci.class_id}, {{}}, drop_{mangle_class(cname)})")
        for fl in ci.all_fields:
            mdef = kind_default(jtype_to_kind(JType(fl.descriptor)))
            w(f"    raw[].f_{safe_ident(fl.mojo_name)} = {mdef}")
        w("    return JRef(raw.unsafe_bitcast[ObjHeader]())")
        w("")

    # 3. Pre-collect MethodIRs
    methods_ir: list[tuple[ClassInfo, Member, MethodIR]] = []
    for cname in sorted(hierarchy.classes):
        ci = hierarchy.classes[cname]
        for m in ci.cf.methods:
            if m.code is None:
                continue
            methods_ir.append((ci, m, lift_method(ci.cf, m)))

    # 4. Emit methods
    for ci, m, ir in methods_ir:
        stats.methods_emitted += 1
        _emit_method(out, hierarchy, ci, m, ir, stats)
        w("")

    # 5. Optional main() entrypoint if entry_class has main([Ljava/lang/String;)V
    if entry_class and entry_class in hierarchy.classes:
        ci = hierarchy.classes[entry_class]
        has_main = any(
            m.is_static() and m.name == "main" and m.descriptor == "([Ljava/lang/String;)V"
            for m in ci.cf.methods
        )
        if has_main:
            main_fn = mangle_method(entry_class, "main", "([Ljava/lang/String;)V")
            w("def main() raises:")
            w("    var statics = alloc_raw[JStatics]()")
            w("    statics.unsafe_write(JStatics())")
            # Run <clinit> if present
            for cname in sorted(hierarchy.classes):
                cci = hierarchy.classes[cname]
                if any(mm.name == "<clinit>" and mm.code is not None for mm in cci.cf.methods):
                    w(f"    {mangle_method(cname, '<clinit>', '()V')}(statics)")
            w("    var argv = new_array[JRef](9, 0)")
            w(f"    {main_fn}(statics, argv)")
            w("    statics.unsafe_deinit_pointee()")
            w("    free_raw(statics)")
            w("")

    return "\n".join(out), stats


def _emit_method(
    out: list[str],
    hierarchy: Hierarchy,
    ci: ClassInfo,
    m: Member,
    ir: MethodIR,
    stats: CodegenStats,
) -> None:
    w = out.append
    fn_name = mangle_method(ir.owner, ir.name, ir.descriptor)

    sig_params = ["_s: JStaticsPtr"]
    param_bind: list[tuple[int, str]] = []
    loc_idx = 0
    if not ir.is_static:
        sig_params.append("arg0: JRef")
        param_bind.append((0, KIND_R))
        loc_idx = 1
    for i, pt in enumerate(ir.params):
        k = jtype_to_kind(pt)
        sig_params.append(f"p{i}: {kind_to_mojo(k)}")
        param_bind.append((loc_idx, k))
        loc_idx += 2 if pt.is_wide else 1

    ret_mojo = "None" if ir.ret_type.is_void else kind_to_mojo(jtype_to_kind(ir.ret_type))
    raises_clause = " raises JThrowable"
    w(f"def {fn_name}({', '.join(sig_params)}){raises_clause} -> {ret_mojo}:")

    # Declare locals, stack slots, temporaries
    declared: set[str] = set()
    for (_, _), val in sorted(ir.locals_used.items()):
        if val.name not in declared:
            declared.add(val.name)
            w(f"    var {val.name}: {kind_to_mojo(val.kind)} = {kind_default(val.kind)}")
    for (_, _), val in sorted(ir.stack_slots.items()):
        if val.name not in declared:
            declared.add(val.name)
            w(f"    var {val.name}: {kind_to_mojo(val.kind)} = {kind_default(val.kind)}")
    for val in ir.temps:
        if val.name not in declared:
            declared.add(val.name)
            w(f"    var {val.name}: {kind_to_mojo(val.kind)} = {kind_default(val.kind)}")

    # Copy incoming params into locals
    p_cursor = 0
    if not ir.is_static:
        lv = ir.locals_used[(0, KIND_R)]
        w(f"    {lv.name} = arg0.copy()")
        p_cursor = 1
    for i, (lidx, k) in enumerate(param_bind[p_cursor:]):
        lv = ir.locals_used[(lidx, k)]
        pname = f"p{i}"
        rhs = f"{pname}.copy()" if k == KIND_R else pname
        w(f"    {lv.name} = {rhs}")

    # Single-block fast path (clean straight-line Mojo)
    if len(ir.blocks) == 1:
        blk = ir.blocks[ir.entry]
        _emit_block_body(out, "    ", hierarchy, ci, blk, stats, single_block=True)
        return

    # General structured dispatch loop (handles any CFG + try/except)
    w("    var _pc: Int32 = 0")
    w("    while True:")
    first = True
    for bpc in sorted(ir.blocks):
        blk = ir.blocks[bpc]
        kw = "if" if first else "elif"
        first = False
        w(f"        {kw} _pc == {bpc}:")
        indent = "            "
        if blk.handlers:
            w(f"{indent}try:")
            _emit_block_body(out, indent + "    ", hierarchy, ci, blk, stats, single_block=False)
            w(f"{indent}except _exc:")
            # Dispatch to first matching handler
            for idx_h, (ctype, hpc) in enumerate(blk.handlers):
                if ctype is None or len(blk.handlers) == 1:
                    w(f"{indent}    s0_R = _exc.obj.copy()")
                    w(f"{indent}    _pc = {hpc}")
                    w(f"{indent}    continue")
                    break
                h_kw = "if" if idx_h == 0 else "elif"
                w(f"{indent}    {h_kw} _exc.class_id >= 0:")
                w(f"{indent}        s0_R = _exc.obj.copy()")
                w(f"{indent}        _pc = {hpc}")
                w(f"{indent}        continue")
        else:
            _emit_block_body(out, indent, hierarchy, ci, blk, stats, single_block=False)


def _copy_if_ref(val: Val) -> str:
    return f"{val.name}.copy()" if val.kind == KIND_R else val.name


def _emit_block_body(
    out: list[str],
    ind: str,
    hierarchy: Hierarchy,
    ci: ClassInfo,
    blk: LiftedBlock,
    stats: CodegenStats,
    *,
    single_block: bool,
) -> None:
    w = out.append
    for st in blk.stmts:
        op, dst, args = st.op, st.dst, st.args
        if op == "const":
            val = args[0]
            if val is None:
                w(f"{ind}{dst.name} = JRef()")
            elif dst.kind == KIND_I:
                w(f"{ind}{dst.name} = Int32({val})")
            elif dst.kind == KIND_J:
                w(f"{ind}{dst.name} = Int64({val})")
            elif dst.kind == KIND_F:
                w(f"{ind}{dst.name} = Float32({val})")
            elif dst.kind == KIND_D:
                w(f"{ind}{dst.name} = Float64({val})")
        elif op == "const_str":
            escaped = args[0].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            w(f'{ind}{dst.name} = new_string("{escaped}")')
        elif op == "copy":
            src: Val = args[0]
            w(f"{ind}{dst.name} = {_copy_if_ref(src)}")
        elif op == "iinc":
            lv, delta = args
            w(f"{ind}{lv.name} += Int32({delta})")
        elif op == "binop":
            bop, lhs, rhs = args
            _emit_binop(w, ind, bop, dst, lhs, rhs)
        elif op == "unop":
            uop, v = args
            _emit_unop(w, ind, uop, dst, v)
        elif op == "new":
            cname = args[0]
            if cname in hierarchy.classes:
                w(f"{ind}{dst.name} = new_{mangle_class(cname)}()")
            else:
                w(f"{ind}{dst.name} = JRef()")
        elif op == "newarray":
            atype, cnt = args
            elem_t = {"Z": "Bool", "B": "Int8", "C": "UInt16", "S": "Int16", "I": "Int32", "J": "Int64", "F": "Float32", "D": "Float64"}.get(atype, "JRef")
            w(f"{ind}{dst.name} = new_array[{elem_t}](8, {cnt.name})")
        elif op == "arraylength":
            arr = args[0]
            w(f"{ind}{dst.name} = array_len[Int32]({arr.name})")
        elif op == "aload_elem":
            kind_c, arr, idx = args
            elem_t = {"i": "Int32", "l": "Int64", "f": "Float32", "d": "Float64", "a": "JRef", "b": "Int8", "c": "UInt16", "s": "Int16"}[kind_c]
            cast_wrap = "" if elem_t in ("Int32", "Int64", "Float32", "Float64", "JRef") else "Int32("
            end_wrap = ")" if cast_wrap else ""
            w(f"{ind}{dst.name} = {cast_wrap}array_get[{elem_t}]({arr.name}, {idx.name}){end_wrap}")
        elif op == "astore_elem":
            kind_c, arr, idx, val = args
            elem_t = {"i": "Int32", "l": "Int64", "f": "Float32", "d": "Float64", "a": "JRef", "b": "Int8", "c": "UInt16", "s": "Int16"}[kind_c]
            vexpr = _copy_if_ref(val) if elem_t == "JRef" else f"{elem_t}({val.name})" if elem_t != "Int32" else val.name
            w(f"{ind}array_set[{elem_t}]({arr.name}, {idx.name}, {vexpr})")
        elif op == "getstatic":
            owner, fname, _ = args
            if owner == "java/lang/System" and fname == "out":
                w(f"{ind}{dst.name} = JRef()")
            else:
                sname = f"sf_{mangle_class(owner)[2:]}_{safe_ident(fname)}"
                w(f"{ind}{dst.name} = _s[].{sname}" + (".copy()" if dst.kind == KIND_R else ""))
        elif op == "putstatic":
            owner, fname, _, val = args
            sname = f"sf_{mangle_class(owner)[2:]}_{safe_ident(fname)}"
            w(f"{ind}_s[].{sname} = {_copy_if_ref(val)}")
        elif op == "getfield":
            owner, fname, _, obj = args
            if owner in hierarchy.classes:
                struct_t = mangle_class(owner) + "Data"
                fl = next((f for f in hierarchy.classes[owner].all_fields if f.name == fname), None)
                mname = safe_ident(fl.mojo_name if fl else fname)
                sfx = ".copy()" if dst.kind == KIND_R else ""
                w(f"{ind}{dst.name} = {obj.name}.non_null().unsafe_bitcast[{struct_t}]()[].f_{mname}{sfx}")
        elif op == "putfield":
            owner, fname, _, obj, val = args
            if owner in hierarchy.classes:
                struct_t = mangle_class(owner) + "Data"
                fl = next((f for f in hierarchy.classes[owner].all_fields if f.name == fname), None)
                mname = safe_ident(fl.mojo_name if fl else fname)
                w(f"{ind}{obj.name}.non_null().unsafe_bitcast[{struct_t}]()[].f_{mname} = {_copy_if_ref(val)}")
        elif op == "instanceof":
            target_cls, obj = args
            if target_cls in hierarchy.classes:
                tci = hierarchy.classes[target_cls]
                w(f"{ind}{dst.name} = is_instance({obj.name}, Int32({tci.class_id}), Int32({tci.max_sub_id}))")
            else:
                w(f"{ind}{dst.name} = Int32(0)")
        elif op == "checkcast":
            target_cls, obj = args
            if target_cls in hierarchy.classes:
                tci = hierarchy.classes[target_cls]
                w(f"{ind}{dst.name} = check_cast({obj.name}, Int32({tci.class_id}), Int32({tci.max_sub_id}))")
            else:
                w(f"{ind}{dst.name} = {obj.name}.copy()")
        elif op == "call":
            _emit_call(w, ind, hierarchy, dst, args, stats)
        elif op == "indy":
            # Placeholder stub for indy in MVP; full lambda/concat lowering follows
            if dst is not None:
                w(f"{ind}{dst.name} = {kind_default(dst.kind)}")
        elif op == "unsupported":
            w(f"{ind}pass  # unsupported opcode: {args[0]}")

    if blk.term is None:
        if single_block:
            w(f"{ind}return")
        return

    top, _, targs = blk.term.op, blk.term.dst, blk.term.args
    if top == "ret":
        if not targs:
            w(f"{ind}return")
        else:
            w(f"{ind}return {_copy_if_ref(targs[0])}")
    elif top == "throw":
        w(f'{ind}raise JThrowable(7, "athrow", {targs[0].name}.copy())')
    elif top == "goto":
        w(f"{ind}_pc = {targs[0]}")
        w(f"{ind}continue")
    elif top == "if1":
        iop, v, tgt, fall = targs
        cond = {
            "ifeq": f"{v.name} == 0",
            "ifne": f"{v.name} != 0",
            "iflt": f"{v.name} < 0",
            "ifge": f"{v.name} >= 0",
            "ifgt": f"{v.name} > 0",
            "ifle": f"{v.name} <= 0",
            "ifnull": f"{v.name}.is_null()",
            "ifnonnull": f"not {v.name}.is_null()",
        }[iop]
        w(f"{ind}if {cond}:")
        w(f"{ind}    _pc = {tgt}")
        w(f"{ind}else:")
        w(f"{ind}    _pc = {fall}")
        w(f"{ind}continue")
    elif top == "if2":
        iop, lhs, rhs, tgt, fall = targs
        cond = {
            "if_icmpeq": f"{lhs.name} == {rhs.name}",
            "if_icmpne": f"{lhs.name} != {rhs.name}",
            "if_icmplt": f"{lhs.name} < {rhs.name}",
            "if_icmpge": f"{lhs.name} >= {rhs.name}",
            "if_icmpgt": f"{lhs.name} > {rhs.name}",
            "if_icmple": f"{lhs.name} <= {rhs.name}",
            "if_acmpeq": f"{lhs.name}.same({rhs.name})",
            "if_acmpne": f"not {lhs.name}.same({rhs.name})",
        }[iop]
        w(f"{ind}if {cond}:")
        w(f"{ind}    _pc = {tgt}")
        w(f"{ind}else:")
        w(f"{ind}    _pc = {fall}")
        w(f"{ind}continue")
    elif top == "switch":
        v, default_pc, table = targs
        first_s = True
        for key, tgt in sorted(table.items()):
            skw = "if" if first_s else "elif"
            first_s = False
            w(f"{ind}{skw} {v.name} == {key}:")
            w(f"{ind}    _pc = {tgt}")
        w(f"{ind}else:")
        w(f"{ind}    _pc = {default_pc}")
        w(f"{ind}continue")


def _emit_binop(w, ind: str, op: str, dst: Val, lhs: Val, rhs: Val) -> None:
    if op in ("idiv", "ldiv", "irem", "lrem"):
        w(f"{ind}if {rhs.name} == 0:")
        w(f'{ind}    raise JThrowable(5, "java/lang/ArithmeticException")')
    sym = {
        "iadd": "+", "ladd": "+", "fadd": "+", "dadd": "+",
        "isub": "-", "lsub": "-", "fsub": "-", "dsub": "-",
        "imul": "*", "lmul": "*", "fmul": "*", "dmul": "*",
        "idiv": "//", "ldiv": "//", "fdiv": "/", "ddiv": "/",
        "irem": "%", "lrem": "%", "frem": "%", "drem": "%",
        "ishl": "<<", "lshl": "<<", "ishr": ">>", "lshr": ">>",
        "iand": "&", "land": "&", "ior": "|", "lor": "|", "ixor": "^", "lxor": "^",
    }.get(op)
    if sym:
        if op in ("ishl", "ishr"):
            w(f"{ind}{dst.name} = {lhs.name} {sym} ({rhs.name} & 31)")
        elif op in ("lshl", "lshr"):
            w(f"{ind}{dst.name} = {lhs.name} {sym} Int64({rhs.name} & 63)")
        else:
            w(f"{ind}{dst.name} = {lhs.name} {sym} {rhs.name}")
    elif op == "iushr":
        w(f"{ind}{dst.name} = Int32(UInt32({lhs.name}) >> UInt32({rhs.name} & 31))")
    elif op == "lushr":
        w(f"{ind}{dst.name} = Int64(UInt64({lhs.name}) >> UInt64({rhs.name} & 63))")
    elif op in ("lcmp", "fcmpl", "fcmpg", "dcmpl", "dcmpg"):
        w(f"{ind}{dst.name} = Int32(1) if {lhs.name} > {rhs.name} else (Int32(-1) if {lhs.name} < {rhs.name} else Int32(0))")


def _emit_unop(w, ind: str, op: str, dst: Val, v: Val) -> None:
    if op.endswith("neg"):
        w(f"{ind}{dst.name} = -{v.name}")
    elif op in ("i2l", "f2l", "d2l"):
        w(f"{ind}{dst.name} = Int64({v.name})")
    elif op in ("l2i", "f2i", "d2i"):
        w(f"{ind}{dst.name} = Int32({v.name})")
    elif op in ("i2f", "l2f", "d2f"):
        w(f"{ind}{dst.name} = Float32({v.name})")
    elif op in ("i2d", "l2d", "f2d"):
        w(f"{ind}{dst.name} = Float64({v.name})")
    elif op == "i2b":
        w(f"{ind}{dst.name} = Int32(Int8({v.name}))")
    elif op == "i2c":
        w(f"{ind}{dst.name} = Int32(UInt16({v.name}))")
    elif op == "i2s":
        w(f"{ind}{dst.name} = Int32(Int16({v.name}))")


def _emit_call(w, ind: str, hierarchy: Hierarchy, dst: Val | None, args: tuple, stats: CodegenStats) -> None:
    cop, owner, mname, mdesc, recv, cargs = args
    builtin = BUILTIN_CALLS.get((owner, mname, mdesc))
    if builtin == "noop":
        return
    if builtin == "println_val":
        w(f"{ind}print({cargs[0].name})")
        return
    if builtin == "println_bool":
        w(f'{ind}print("true" if {cargs[0].name} != 0 else "false")')
        return
    if builtin == "println_str":
        w(f"{ind}print(string_value({cargs[0].name}))")
        return
    if builtin == "abs_i":
        w(f"{ind}{dst.name} = {cargs[0].name} if {cargs[0].name} >= 0 else -{cargs[0].name}")
        return
    if builtin == "max_ii":
        w(f"{ind}{dst.name} = {cargs[0].name} if {cargs[0].name} >= {cargs[1].name} else {cargs[1].name}")
        return
    if builtin == "min_ii":
        w(f"{ind}{dst.name} = {cargs[0].name} if {cargs[0].name} <= {cargs[1].name} else {cargs[1].name}")
        return

    target_owner = owner
    if cop in ("invokevirtual", "invokeinterface"):
        devirt = hierarchy.resolve_devirtualized(owner, mname, mdesc)
        if devirt is not None:
            target_owner = devirt
            stats.calls_devirtualized += 1
        else:
            stats.calls_virtual += 1
            # Polymorphic dispatch: emit runtime class_id switch across concrete overrides
            sub_impls = _concrete_overrides(hierarchy, owner, mname, mdesc)
            if sub_impls:
                arg_exprs = [_copy_if_ref(a) for a in cargs]
                rhs_prefix = f"{dst.name} = " if dst is not None else ""
                cid_var = f"_cid_{recv.name}_{id(args) & 0xFFFF}"
                w(f"{ind}var {cid_var} = {recv.name}.class_id()")
                for idx_s, (sub_cid, impl_owner) in enumerate(sub_impls):
                    skw = "if" if idx_s == 0 else "elif"
                    fn_m = mangle_method(impl_owner, mname, mdesc)
                    call_s = f"{fn_m}({', '.join(['_s', recv.name + '.copy()', *arg_exprs])})"
                    w(f"{ind}{skw} {cid_var} == {sub_cid}:")
                    w(f"{ind}    {rhs_prefix}{call_s}")
                w(f"{ind}else:")
                w(f'{ind}    raise JThrowable(8, "AbstractMethodError: {owner}.{mname}")')
                return

    if target_owner not in hierarchy.classes:
        if dst is not None:
            w(f"{ind}{dst.name} = {kind_default(dst.kind)}  # external: {owner}.{mname}{mdesc}")
        else:
            w(f"{ind}pass  # external: {owner}.{mname}{mdesc}")
        return

    fn_m = mangle_method(target_owner, mname, mdesc)
    call_list = ["_s"]
    if recv is not None:
        call_list.append(f"{recv.name}.copy()")
    call_list.extend(_copy_if_ref(a) for a in cargs)
    call_expr = f"{fn_m}({', '.join(call_list)})"
    if dst is not None:
        w(f"{ind}{dst.name} = {call_expr}")
    else:
        w(f"{ind}{call_expr}")


def _concrete_overrides(hierarchy: Hierarchy, owner: str, name: str, desc: str) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    for sub in hierarchy._subtypes(owner):
        ci = hierarchy.classes[sub]
        if ci.cf.is_interface or (ci.cf.access & ACC_ABSTRACT):
            continue
        cur: str | None = sub
        while cur and cur in hierarchy.classes:
            cci = hierarchy.classes[cur]
            if any(
                not mm.is_static() and not (mm.access & ACC_ABSTRACT) and mm.name == name and mm.descriptor == desc
                for mm in cci.cf.methods
            ):
                out.append((ci.class_id, cur))
                break
            cur = cci.cf.super_name
    return out
